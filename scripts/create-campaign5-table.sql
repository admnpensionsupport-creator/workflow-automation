-- Creates the "Cold Email Campaign 5" table for the Campbell USD & San Jose USD 3-email drip.
-- Mirrors the schema of "Cold Email Campaign 4" with sequence_step supporting
-- steps 1–3 for the three-email sequence.
--
-- Run this ONCE in the Supabase SQL Editor before importing contacts.

CREATE TABLE IF NOT EXISTS "Cold Email Campaign 5" (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          text NOT NULL,
  name           text,
  title          text,
  district       text,
  batch          text DEFAULT 'campbell-sjusd',
  sequence_step  integer DEFAULT 1,
  last_emailed_at timestamptz,
  subject        text,
  body           text,
  opted_out      boolean DEFAULT false,
  unsubscribed_at timestamptz,
  unsubscribe_reason text,
  created_at     timestamptz DEFAULT now()
);

-- Index for fast unsubscribe lookups.
CREATE INDEX IF NOT EXISTS campaign5_unsubscribed_at_idx
  ON "Cold Email Campaign 5" (unsubscribed_at)
  WHERE unsubscribed_at IS NOT NULL;

-- Index for the workflow query (active, eligible contacts).
CREATE INDEX IF NOT EXISTS campaign5_active_contacts_idx
  ON "Cold Email Campaign 5" (sequence_step, opted_out)
  WHERE opted_out IS DISTINCT FROM true AND sequence_step <= 3;

